/**
 * 확장 기획 4장 "동행 서비스": 기존 바운티는 전문가가 원격으로 결과물(파일)을
 * 제출하는 방식(REMOTE)이었는데, 부동산 임장 동행·중고차 점검 동행처럼 전문가가
 * "실제 현장에 같이 가야" 하는 의뢰가 추가됐다. 이건 완전히 새로운 도메인이 아니라
 * 기존 도메인(부동산 권리분석, 차량 정밀 기술 진단 등)에 붙는 "진행 방식"의
 * 차이라서, DomainType을 늘리는 대신 Bounty에 이 필드를 별도로 둔다.
 *
 * REMOTE   : 기존 방식 - 전문가가 원격으로 작업해서 파일을 제출
 * COMPANION: 동행 방식 - 전문가가 예약된 일시·장소에 실제로 동행, 종료 후 소견서(파일) 제출
 */
export enum ServiceType {
  REMOTE = 'REMOTE',
  COMPANION = 'COMPANION',
}
