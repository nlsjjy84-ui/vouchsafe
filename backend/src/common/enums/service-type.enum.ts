/**
 * 동행 서비스 확장 (Phase 2). 기존 15개 도메인은 전부 "원격으로 결과물만 주고받는" 거래를
 * 전제로 설계됐는데, 건축물 하자 진단·차량 정밀 진단·부동산 권리분석처럼 원래 현장 방문이
 * 필요한 도메인들은 "전문가가 의뢰인과 직접 만나 동행한다"는 별도 거래 형태가 필요하다.
 * ServiceType은 도메인과 별개 축이다 — 같은 도메인이라도 REMOTE(원격 진단/자문)로도,
 * COMPANION(현장 동행)으로도 거래될 수 있다.
 */
export enum ServiceType {
  REMOTE = 'REMOTE', // 원격 - 기존 방식. 결과물(파일)을 제출하고 검수받는다
  COMPANION = 'COMPANION', // 동행 - 지정된 시간/장소에서 전문가가 의뢰인과 직접 만난다
}
