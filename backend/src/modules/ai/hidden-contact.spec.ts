import { hiddenContact, ruleBasedRisk } from './features/risk-check.feature';

/**
 * 연락처 우회 표현 — 수수료를 피해 밖에서 거래하려고 연락처를 한글·띄어쓰기·기호로 쪼개 쓰는 경우.
 * 잡아야 하는 문장과, 잡으면 안 되는 보통 문장을 같이 고정해 둔다(잘못 막힘 방지).
 */
describe('hiddenContact', () => {
  const blocked = [
    '공일공 일이삼사 오육칠팔',
    '영일영-1234-오육칠팔',
    '공1공 12삼4 5678',
    '0 1 0 . 1 2 3 4 . 5 6 7 8',
    '010 1234 5678',
    '０１０１２３４５６７８',
    '국민 123456 78 901234',
    '카.톡 주세요',
    '카 톡 아이디 알려드릴게요',
    '까톡으로 연락 주세요',
    'ㅋㅌ 주세요',
    'k a k a o 로 와요',
    '오픈 채팅방 만들게요',
    '텔레 주세요',
    '인스타 DM 주세요',
    '디엠 주세요',
    '디코로 연락',
    'abc 골뱅이 지메일 닷컴',
    '번호 알려주세요',
    '전화 주세요',
  ];
  const allowed = [
    '이사 오일 걸려요',
    '150만 원이고 1,500,000원도 됩니다',
    '2026-10-14 10:00에 가능해요',
    '일이 삼일 정도 걸립니다',
    '주말에도 가능하신가요?',
    '디코딩 오류 점검도 하나요',
    '텔레비전 설치 위치도 봐 주세요',
    '가이드라인 대로 합니다',
    '카카오페이 결제 연동 점검',
    '이 상품은 오일 교환 포함인가요?',
    '네이버 리뷰 점검도 되나요',
    'DB 쿼리 3개, 인덱스 2개',
    '연락은 어떻게 하나요?',
    '아이디어 회의도 해 주시나요',
  ];

  it.each(blocked)('잡는다: %s', (t) => {
    expect(hiddenContact(t)).not.toBeNull();
    expect(ruleBasedRisk(t).some((s) => s.type === 'CONTACT')).toBe(true);
  });

  it.each(allowed)('통과시킨다: %s', (t) => {
    expect(hiddenContact(t)).toBeNull();
  });
});
